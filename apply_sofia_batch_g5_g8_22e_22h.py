def roadmap_update(content: str) -> str:
    for name, anchor in (("Batch G status", G_OLD), ("Batch 22 status", D_OLD),
                         ("Next development gate", GATE_HEADING)):
        if content.count(anchor) != 1:
            raise ValueError(f"Expected exactly one {name} anchor; roadmap changed; no files written.")
    prefix, tail = content.split(GATE_HEADING, 1)
    if "**Batch G: Personality Architecture.**" not in tail:
        raise ValueError("Roadmap gate changed; refusing unreviewed replacement.")
    updated = prefix.replace(G_OLD, G_NEW).replace(D_OLD, D_NEW)
    updated += GATE_HEADING + "\n\n"
    updated += "**Current gate:** G5–G8 and 22E–22H have been prepared for offline verification. "
    updated += "The real Ollama personality review and authenticated multi-machine transport, "
    updated += "remote agent, durable audit/replay protection, and live LAN verification remain open. "
    updated += "Do not claim the full batches are operationally complete on mock-test evidence alone. "
    updated += "See [`docs/development/batch-g5-g8-and-22e-22h.md`](docs/development/batch-g5-g8-and-22e-22h.md).\n"
    return updated


def run_git(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *args], capture_output=True, text=True, check=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Preflight and preview; no changes")
    args = parser.parse_args()
    root = run_git("rev-parse", "--show-toplevel")
    if root.returncode or Path(root.stdout.strip()).resolve() != Path.cwd().resolve():
        raise SystemExit("Run from the Sofía repository root. Nothing changed.")
    missing = [name for name in REQUIRED_PREDECESSORS if not Path(name).is_file()]
    if missing:
        raise SystemExit(f"Missing required committed predecessor(s): {missing}. Nothing changed.")
    tracked = run_git("ls-files", "--error-unmatch", "--", *REQUIRED_PREDECESSORS)
    if tracked.returncode:
        raise SystemExit("Expected G1–G4 / 22A–22D files are not all Git-tracked; no changes.")
    if run_git("status", "--porcelain", "--", "ROADMAP.md").stdout.strip():
        raise SystemExit("ROADMAP.md has local edits or staged changes. Review first; no changes.")
    collisions = [name for name in FILES if Path(name).exists()]
    if collisions:
        raise SystemExit(f"File target(s) already exist; refusing overwrite: {collisions}. Nothing changed.")
    for name, content in FILES.items():
        if hashlib.sha256(content.encode("utf-8")).hexdigest() != EXPECTED_SHA256[name]:
            raise SystemExit(f"Embedded content checksum mismatch: {name}; nothing changed.")
        if name.endswith(".py"):
            ast.parse(content, filename=name)
    roadmap = Path("ROADMAP.md")
    original = roadmap.read_text(encoding="utf-8-sig")
    updated = roadmap_update(original)
    print(f"Preflight OK. {len(FILES)} new source/test/docs files; ROADMAP.md update:")
    for name in FILES:
        print("  +", name)
    for line in difflib.unified_diff(original.splitlines(), updated.splitlines(),
                                     fromfile="a/ROADMAP.md", tofile="b/ROADMAP.md", lineterm=""):
        print(line)
    if args.check:
        print("--check: no files changed.")
        return
    written: list[Path] = []
    try:
        for name, content in FILES.items():
            dest = Path(name)
            dest.parent.mkdir(parents=True, exist_ok=True)
            with dest.open("x", encoding="utf-8", newline="\n") as stream:
                written.append(dest)
                stream.write(content)
        # Update roadmap last, after all collision/checksum/AST validation.
        with roadmap.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(updated)
    except Exception:
        # Preserve user's exact original roadmap content if roadmap update failed.
        # No modifications to any other previously existing file.
        with roadmap.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write(original)
        for dest in reversed(written):
            dest.unlink(missing_ok=True)
        raise
    print("Installed combined G5–G8 + 22E–22H offline package; NO commit/push/network/state changes.")
    print("Actual Ollama and secure multi-machine verification are STILL PENDING.")


if __name__ == "__main__":
    main()
