"""Install one coherent PUBLIC waist-up 2D avatar pack, without touching DB.

The legacy public outfit sprites and the modular face/fox sprite atlas were
previously generated by separate commands. This installer composes and checks
both in precisely the layout expected by the live TkLayered2DRenderer:

  <root>/outfits/<canonical public outfit ID>/manifest.json + PNGs
  <root>/character/manifest.json + separate face/ear/tail PNGs

All outputs are starter art and MUST NOT be advertised as reviewed final
illustrations. Never imports/loads protected private wardrobe artwork.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from hashlib import sha256
import json
from pathlib import Path
import shutil
import tempfile

from .presentation import (
    AppearanceState, AttireMode, AudienceScope, PresentationProjection,
)
from .vtuber_asset_bundle import (
    Avatar2DArtSelection, _read_bundle, _read_file, _relative_png, _verify_png,
)
from .vtuber_character_bundle import _validated_manifest, load_selected_character_sprites
from .vtuber_character_parts import (
    character_part_options, generate_public_character_parts,
)
from .vtuber_character_selection import CharacterPartSelection
from .vtuber_layer_stack import assemble_avatar2d_layers
from .vtuber_starter_art import generate_public_outfit_art
from .wardrobe_catalog import build_starter_wardrobe
from .wardrobe_matrix import build_wardrobe_matrix


@dataclass(frozen=True, slots=True)
class PublicAvatar2DInstallReceipt:
    output: Path
    outfits: tuple[str, ...]
    outfit_sprites: int
    character_sprites: int
    status: str = "verified_procedural_starter_not_artist_approved"


def _public_outfit_ids(catalog, *, all_public: bool, outfit_id: str) -> tuple[str, ...]:
    approved = {
        preset.outfit_id: preset for preset in catalog.presets
        if not preset.private_only
    }
    if all_public:
        if not approved:
            raise ValueError("no approved public wardrobe outfits available")
        return tuple(sorted(approved))
    if outfit_id not in approved:
        raise ValueError("requested outfit is not an approved public preset")
    return (outfit_id,)


def _verify_public_outfit(root: Path, preset, catalog) -> int:
    art = _read_bundle(
        root / "outfits" / preset.outfit_id,
        audience=AudienceScope.PUBLIC,
        attire=AttireMode.CLOTHED,
        outfit_id=preset.outfit_id,
    )
    try:
        matrix = build_wardrobe_matrix(catalog, preset.item_ids)
        projection = PresentationProjection(
            audience=AudienceScope.PUBLIC,
            source_revision=1,
            attire=AttireMode.CLOTHED,
            outfit_id=preset.outfit_id,
            item_ids=preset.item_ids,
            appearance=AppearanceState(
                hairstyle="layered",
                hair_color="deep crimson",
                tail_color="dark violet",
            ),
            private_fallback_used=False,
            reason="source-linked public 2D installation check",
        )
        layers = assemble_avatar2d_layers(
            Avatar2DArtSelection(
                "public", projection, art, "checked public asset bundle",
            ),
            matrix=matrix,
        )
        return len(layers.draw_layers)
    finally:
        art.close()


def _verify_character_pack(root: Path) -> int:
    character = root / "character"
    entries = _validated_manifest(character)
    # Validate every variant (including optional wink/tail-flick frames),
    # not merely the 12 default choices that will be drawn at startup.
    seen = 0
    for part in entries.values():
        image = _read_file(
            character, _relative_png(part["path"]), limit=6 * 1024 * 1024,
        )
        if sha256(image).hexdigest() != part["sha256"]:
            raise ValueError("character asset checksum mismatch")
        _verify_png(image)
        if (
            int.from_bytes(image[16:20], "big") != 320
            or int.from_bytes(image[20:24], "big") != 400
        ):
            raise ValueError("character sprite has mismatched canvas")
        seen += 1
    opts = character_part_options()
    starter = CharacterPartSelection(
        source_revision=1,
        groups=tuple(sorted((group, variants[0]) for group, variants in opts.items())),
    )
    if len(load_selected_character_sprites(character, starter)) != len(opts):
        raise ValueError("character group pack failed selection")
    return seen


def prepare_public_avatar2d(
    output: Path,
    *,
    all_public: bool = False,
    outfit_id: str = "day.default",
) -> PublicAvatar2DInstallReceipt:
    """Build, verify, then atomically move one complete public sprite tree.

    Refuses an existing target; never overwrites reviewed art. Work is staged
    next to output to prevent partially generated active packs from being
    picked up by a running desktop. No canonical DB or host configuration is
    created/modified by this function.
    """
    if not isinstance(output, Path):
        raise TypeError("explicit output Path required")
    if output.exists() or output.is_symlink():
        raise FileExistsError("refusing to overwrite existing avatar 2D art")
    catalog = build_starter_wardrobe()
    selected = _public_outfit_ids(
        catalog, all_public=all_public, outfit_id=outfit_id,
    )
    approved = {p.outfit_id: p for p in catalog.presets if not p.private_only}
    parent = output.parent
    if parent.is_symlink():
        raise ValueError("symlinked output parent not allowed")
    parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(tempfile.mkdtemp(prefix=".avatar2d-staging-", dir=parent))
    count = 0
    try:
        for name in selected:
            result = generate_public_outfit_art(
                catalog,
                outfit_id=name,
                destination=temporary / "outfits" / name,
            )
            assert result.asset_count > 0
        generate_public_character_parts(temporary / "character")
        for name in selected:
            count += _verify_public_outfit(temporary, approved[name], catalog)
        characters = _verify_character_pack(temporary)
        if output.exists() or output.is_symlink():
            raise FileExistsError("avatar 2D destination changed during generation")
        temporary.rename(output)
    finally:
        if temporary.exists():
            shutil.rmtree(temporary)
    return PublicAvatar2DInstallReceipt(
        output=output,
        outfits=selected,
        outfit_sprites=count,
        character_sprites=characters,
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install verified PUBLIC 2D waist-up sprite pack")
    parser.add_argument("--output", required=True, type=Path)
    choices = parser.add_mutually_exclusive_group()
    choices.add_argument("--all-public", action="store_true")
    choices.add_argument("--outfit", default="day.default")
    args = parser.parse_args(argv)
    result = prepare_public_avatar2d(
        args.output, all_public=args.all_public, outfit_id=args.outfit,
    )
    print(
        f"PUBLIC 2D PACK READY: {len(result.outfits)} outfits, "
        f"{result.outfit_sprites} outfit layers, "
        f"{result.character_sprites} character variants.\n"
        f"Quality: {result.status}.\n"
        f"PowerShell: $env:SOFIA_AVATAR2D_PUBLIC_ROOT = '{result.output}'\n"
        "Then launch Sofía normally with python -m sofia."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
