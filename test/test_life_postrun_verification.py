"""CA-3014 completion evidence is reviewed after creation budget is consumed.

Authored for the deferred host acceptance campaign; not executed here.
"""
from datetime import timedelta

from sofia.life.model import ProjectStatus
from sofia.run.work import WorkStatus
from test.test_life_project_forge import infrastructure, active_project, wait_for_job


def test_completed_run_artifact_still_gets_independent_review_after_daily_budget(
    tmp_path,
):
    life, _goals, now = infrastructure(tmp_path)
    try:
        project, _ = active_project(life, now)
        initial = life.tick(now=now + timedelta(seconds=3))
        assert initial["scheduled"] == 1
        job = wait_for_job(life, life.store.jobs(project.project_id)[0])
        assert job.status is WorkStatus.COMPLETED
        # Already-generated bytes may consume 100% of daily storage budget.
        # This is NOT permission to draft more work, but it must not hide the
        # independently inspectable completed artifact from verification.
        day = (now + timedelta(seconds=5)).date()
        life.store.add_usage(
            project_id=project.project_id, usage_day=day,
            cpu_seconds=0,gpu_seconds=0,wall_seconds=0,
            storage_bytes=project.brief.resource_budget.storage_bytes,
        )
        assert life.select_activity(
            now=now + timedelta(seconds=5),
            busy=False, resource_pressure=0,
        ).project_id is None
        reviewed = life.tick(now=now + timedelta(seconds=6))
        assert reviewed["selection"] == "project"
        assert reviewed["project_id"] == project.project_id
        assert reviewed["scheduled"] == 0
        assert reviewed["follow_through"] in {
            "independently_completed",
            "needs_independent_objective_review",
            "reviewed_judgment_requires_decision",
        }
        assert len(life.store.evaluations(project.project_id)) <= 1
    finally:
        life.close()


def test_chosen_quiet_prevents_optional_artifact_evaluation_until_expiry(tmp_path):
    life, _goals, now = infrastructure(tmp_path)
    try:
        project, _ = active_project(life, now)
        life.tick(now=now + timedelta(seconds=3))
        job = wait_for_job(life, life.store.jobs(project.project_id)[0])
        assert job.status is WorkStatus.COMPLETED
        life.choose_inactivity(
            reason="A quiet period comes first",
            until=now + timedelta(hours=1),
            now=now + timedelta(seconds=4),
        )
        result = life.tick(now=now + timedelta(seconds=5))
        assert result["selection"] == "inactivity"
        assert not life.store.evaluations(project.project_id)
        later = life.tick(now=now + timedelta(hours=2))
        assert later["selection"] == "project"
        assert later["project_id"] == project.project_id
    finally:
        life.close()
